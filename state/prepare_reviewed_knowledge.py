for game in read_games():
    key='for-sale' if game['n'].lower()=='for sale' else game['id']
    sources=knowledge(game)
    entries=[]
    for question, aliases, answer, quote in catalog.get(key,[]):
        source=next((source for source in sources if quote in source.content),None)
        if source is None:
            raise ValueError(f'Inspected source missing: {key} / {question}')
        entries.append({'question':question,'aliases':aliases,'answer':answer,'source_id':source.id,'quote':quote,'reviewed':True})
    if entries:
        game['verified_qa']=entries
        write_game(Game(**game))
        print(f"{game['n']}: {len(entries)} inspected Q&A entries",flush=True)
